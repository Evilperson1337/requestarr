BEGIN;

-- Acceptance time is audit metadata assigned by PostgreSQL. It deliberately is
-- not part of command identity, so a retry remains a replay even at a later time.
ALTER TABLE inventory_accepted_observations
    ALTER COLUMN accepted_at SET DEFAULT statement_timestamp(),
    ADD COLUMN acceptance_order BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE UNIQUE INDEX inventory_accepted_observations_scope_order_key
    ON inventory_accepted_observations(source_id, configuration_revision, acceptance_order);
ALTER TABLE inventory_accepted_observations
    ADD COLUMN predecessor_observation_id UUID NULL
        REFERENCES inventory_accepted_observations(id) ON DELETE RESTRICT;

CREATE OR REPLACE FUNCTION validate_accepted_observation_transition(observation UUID) RETURNS VOID
LANGUAGE plpgsql AS $$
DECLARE
    source UUID;
    revision BIGINT;
    predecessor UUID;
    acceptance BIGINT;
    latest UUID;
BEGIN
    SELECT source_id, configuration_revision, predecessor_observation_id, acceptance_order
      INTO source, revision, predecessor, acceptance
      FROM inventory_accepted_observations WHERE id = observation;
    IF NOT FOUND THEN
        RETURN;
    END IF;

    -- A commit must carry the complete coverage proof even if it has no items.
    IF (SELECT count(*) FROM inventory_accepted_observation_coverage WHERE observation_id = observation) <>
       (SELECT count(*) * jsonb_array_length(enabled_media_types)
          FROM inventory_source_configuration_revisions r
          JOIN inventory_source_configuration_revision_selected_libraries l
            ON l.source_id = r.source_id AND l.revision = r.revision
         WHERE r.source_id = source AND r.revision = revision
         GROUP BY r.enabled_media_types) THEN
        RAISE EXCEPTION 'accepted observation must prove every configured library and media type pair' USING ERRCODE = '23514';
    END IF;

    SELECT id INTO latest
      FROM inventory_accepted_observations
     WHERE source_id = source AND configuration_revision = revision
     ORDER BY acceptance_order DESC
     LIMIT 1;
    IF latest = observation THEN
        IF predecessor IS NOT NULL AND NOT EXISTS (
            SELECT 1 FROM inventory_accepted_observations p
             WHERE p.id = predecessor AND p.source_id = source AND p.configuration_revision = revision
               AND p.acceptance_order < acceptance
        ) THEN
            RAISE EXCEPTION 'accepted observation predecessor is outside its transition scope' USING ERRCODE = '23514';
        END IF;
        IF predecessor IS NULL AND EXISTS (
            SELECT 1 FROM inventory_accepted_observations p
             WHERE p.source_id = source AND p.configuration_revision = revision AND p.id <> observation
        ) THEN
            RAISE EXCEPTION 'accepted observation transition lacks predecessor provenance' USING ERRCODE = '23514';
        END IF;
        IF predecessor IS NOT NULL AND predecessor <> (
            SELECT p.id FROM inventory_accepted_observations p
             WHERE p.source_id = source AND p.configuration_revision = revision AND p.id <> observation
             ORDER BY p.acceptance_order DESC LIMIT 1
        ) THEN
            RAISE EXCEPTION 'accepted observation predecessor is not the prior accepted state' USING ERRCODE = '23514';
        END IF;

        -- The projection is exactly the latest accepted item evidence. This is
        -- intentionally a set comparison, not a reimplementation of the Go diff.
        IF EXISTS (
            (SELECT remote_library_id, source_item_id, media_type, title, external_url, item_revision
               FROM inventory_accepted_observation_items WHERE observation_id = observation
             EXCEPT
             SELECT remote_library_id, source_item_id, media_type, title, external_url, item_revision
               FROM inventory_desired_source_revision_items
              WHERE source_id = source AND configuration_revision = revision)
            UNION ALL
            (SELECT remote_library_id, source_item_id, media_type, title, external_url, item_revision
               FROM inventory_desired_source_revision_items
              WHERE source_id = source AND configuration_revision = revision
             EXCEPT
             SELECT remote_library_id, source_item_id, media_type, title, external_url, item_revision
               FROM inventory_accepted_observation_items WHERE observation_id = observation)
        ) THEN
            RAISE EXCEPTION 'desired projection must exactly equal the latest accepted observation evidence' USING ERRCODE = '23514';
        END IF;

        -- Events are a complete, deterministic accounting of the predecessor to
        -- current transition. They cannot be independently forged or omitted.
        IF EXISTS (
            (SELECT 'added'::TEXT, n.remote_library_id, n.source_item_id, n.media_type
               FROM inventory_accepted_observation_items n
              WHERE n.observation_id = observation AND NOT EXISTS (SELECT 1 FROM inventory_accepted_observation_items o WHERE o.observation_id IS NOT DISTINCT FROM predecessor AND o.remote_library_id = n.remote_library_id AND o.source_item_id = n.source_item_id)
             EXCEPT SELECT change_kind, remote_library_id, source_item_id, media_type FROM inventory_accepted_observation_events WHERE observation_id = observation)
            UNION ALL
            (SELECT 'updated'::TEXT, n.remote_library_id, n.source_item_id, n.media_type
               FROM inventory_accepted_observation_items n JOIN inventory_accepted_observation_items o ON o.observation_id IS NOT DISTINCT FROM predecessor AND o.remote_library_id = n.remote_library_id AND o.source_item_id = n.source_item_id
              WHERE n.observation_id = observation AND (n.media_type, n.title, n.external_url, n.item_revision) IS DISTINCT FROM (o.media_type, o.title, o.external_url, o.item_revision)
             EXCEPT SELECT change_kind, remote_library_id, source_item_id, media_type FROM inventory_accepted_observation_events WHERE observation_id = observation)
            UNION ALL
            (SELECT 'removed'::TEXT, o.remote_library_id, o.source_item_id, o.media_type
               FROM inventory_accepted_observation_items o
              WHERE o.observation_id IS NOT DISTINCT FROM predecessor AND NOT EXISTS (SELECT 1 FROM inventory_accepted_observation_items n WHERE n.observation_id = observation AND n.remote_library_id = o.remote_library_id AND n.source_item_id = o.source_item_id)
             EXCEPT SELECT change_kind, remote_library_id, source_item_id, media_type FROM inventory_accepted_observation_events WHERE observation_id = observation)
            UNION ALL
            (SELECT change_kind, remote_library_id, source_item_id, media_type FROM inventory_accepted_observation_events WHERE observation_id = observation
             EXCEPT
             (SELECT 'added'::TEXT, n.remote_library_id, n.source_item_id, n.media_type FROM inventory_accepted_observation_items n WHERE n.observation_id = observation AND NOT EXISTS (SELECT 1 FROM inventory_accepted_observation_items o WHERE o.observation_id IS NOT DISTINCT FROM predecessor AND o.remote_library_id = n.remote_library_id AND o.source_item_id = n.source_item_id)
              UNION ALL SELECT 'updated'::TEXT, n.remote_library_id, n.source_item_id, n.media_type FROM inventory_accepted_observation_items n JOIN inventory_accepted_observation_items o ON o.observation_id IS NOT DISTINCT FROM predecessor AND o.remote_library_id = n.remote_library_id AND o.source_item_id = n.source_item_id WHERE n.observation_id = observation AND (n.media_type, n.title, n.external_url, n.item_revision) IS DISTINCT FROM (o.media_type, o.title, o.external_url, o.item_revision)
              UNION ALL SELECT 'removed'::TEXT, o.remote_library_id, o.source_item_id, o.media_type FROM inventory_accepted_observation_items o WHERE o.observation_id IS NOT DISTINCT FROM predecessor AND NOT EXISTS (SELECT 1 FROM inventory_accepted_observation_items n WHERE n.observation_id = observation AND n.remote_library_id = o.remote_library_id AND n.source_item_id = o.source_item_id)))
        ) THEN
            RAISE EXCEPTION 'accepted observation events must exactly prove the deterministic transition' USING ERRCODE = '23514';
        END IF;
        IF EXISTS (
            SELECT 1 FROM (
                SELECT ordinal,
                       row_number() OVER (ORDER BY CASE change_kind WHEN 'added' THEN 1 WHEN 'updated' THEN 2 ELSE 3 END, remote_library_id, source_item_id) AS expected_ordinal
                  FROM inventory_accepted_observation_events
                 WHERE observation_id = observation
            ) ordered_events
             WHERE ordinal <> expected_ordinal
        ) THEN
            RAISE EXCEPTION 'accepted observation event ordinals must use deterministic transition order' USING ERRCODE = '23514';
        END IF;
    END IF;
END $$;

CREATE FUNCTION validate_accepted_observation_transition_trigger() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    PERFORM validate_accepted_observation_transition(COALESCE(NEW.observation_id, OLD.observation_id));
    RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER inventory_accepted_observations_complete
AFTER INSERT ON inventory_accepted_observations DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_accepted_observation_transition_trigger();
CREATE CONSTRAINT TRIGGER inventory_accepted_observation_items_transition
AFTER INSERT ON inventory_accepted_observation_items DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_accepted_observation_transition_trigger();
CREATE CONSTRAINT TRIGGER inventory_accepted_observation_events_transition
AFTER INSERT ON inventory_accepted_observation_events DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_accepted_observation_transition_trigger();
CREATE TRIGGER inventory_accepted_observation_events_scope
BEFORE INSERT OR UPDATE ON inventory_accepted_observation_events
FOR EACH ROW EXECUTE FUNCTION validate_accepted_observation_scope();

CREATE FUNCTION validate_desired_projection_change() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    changed_source UUID;
    changed_revision BIGINT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        changed_source := OLD.source_id;
        changed_revision := OLD.configuration_revision;
    ELSE
        changed_source := NEW.source_id;
        changed_revision := NEW.configuration_revision;
    END IF;
    PERFORM validate_accepted_observation_transition(
        (SELECT id FROM inventory_accepted_observations
          WHERE source_id = changed_source AND configuration_revision = changed_revision
          ORDER BY acceptance_order DESC LIMIT 1));
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER inventory_desired_source_revision_items_complete
AFTER INSERT OR UPDATE OR DELETE ON inventory_desired_source_revision_items
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_desired_projection_change();

COMMIT;
